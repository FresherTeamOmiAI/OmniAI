-- SQL cho PostgreSQL 16 (Flyway). pgvector bật ở V3.

CREATE TABLE product (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku              VARCHAR(64)   NOT NULL UNIQUE,
    name             VARCHAR(255)  NOT NULL,
    brand            VARCHAR(255),
    category         VARCHAR(255),
    skin_types       VARCHAR(255),
    ingredients_inci VARCHAR(4000),
    size_ml          INTEGER,
    pao_months       INTEGER,
    price_web        BIGINT,
    price_shopee     BIGINT,
    price_tiktok     BIGINT,
    stock            INTEGER       NOT NULL DEFAULT 0,
    active           BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE customer (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(255),
    email        VARCHAR(255) UNIQUE,
    phone        VARCHAR(20)  UNIQUE,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE channel_identity (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT REFERENCES customer (id),
    channel     VARCHAR(20)  NOT NULL,
    external_id VARCHAR(255) NOT NULL,
    linked_by   VARCHAR(30),
    confidence  DOUBLE PRECISION,
    consent_at  TIMESTAMP WITH TIME ZONE,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_channel_identity UNIQUE (channel, external_id)
);

CREATE INDEX idx_channel_identity_customer ON channel_identity (customer_id);

-- Lưu hội thoại mọi kênh (US-11, T-11.1, decisions #30). Owner: TuTM.
-- Mỗi lượt chat = 1 dòng IN (tin khách) + 1 dòng OUT (câu bot). Luật vi phạm của câu OUT nằm ở bảng con.

CREATE TABLE conversation (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel         VARCHAR(20)  NOT NULL,
    -- CanonicalMessage.conversationId, vd. web:<session>, tiktok:<conversation_id>
    external_id     VARCHAR(255) NOT NULL,
    channel_user_id VARCHAR(255) NOT NULL,
    customer_id     BIGINT REFERENCES customer (id),
    started_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    last_message_at TIMESTAMP WITH TIME ZONE NOT NULL,
    message_count   INT NOT NULL DEFAULT 0,
    CONSTRAINT uq_conversation UNIQUE (channel, external_id)
);

CREATE INDEX ix_conversation_channel_last ON conversation (channel, last_message_at DESC);
CREATE INDEX ix_conversation_last ON conversation (last_message_at DESC);

CREATE TABLE conversation_message (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT       NOT NULL REFERENCES conversation (id) ON DELETE CASCADE,
    direction       VARCHAR(3)   NOT NULL,
    -- IN: messageId của tin khách; OUT: messageId của tin mà câu bot trả lời
    message_id      VARCHAR(255) NOT NULL,
    -- IN: tin khách; OUT: finalText (câu khách thực nhận sau policy)
    text            TEXT         NOT NULL,
    -- Chỉ OUT: câu gốc của AI Brain trước policy
    raw_text        TEXT,
    blocked         BOOLEAN      NOT NULL DEFAULT FALSE,
    handoff         BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_conversation_message UNIQUE (conversation_id, direction, message_id),
    CONSTRAINT ck_conversation_message_direction CHECK (direction IN ('IN', 'OUT'))
);

CREATE INDEX ix_conversation_message_conv_time ON conversation_message (conversation_id, created_at, id);

CREATE TABLE message_violation (
    message_id BIGINT       NOT NULL REFERENCES conversation_message (id) ON DELETE CASCADE,
    position   INT          NOT NULL,
    rule_id    VARCHAR(100) NOT NULL,
    action     VARCHAR(10)  NOT NULL,
    matched    TEXT,
    PRIMARY KEY (message_id, position),
    CONSTRAINT ck_message_violation_action CHECK (action IN ('BLOCK', 'REDACT', 'REPLACE'))
);

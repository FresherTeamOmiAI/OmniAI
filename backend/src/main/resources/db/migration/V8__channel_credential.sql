-- Ủy quyền OAuth2 của shop trên kênh sàn (US-25, decisions #27). TikTok Shop dùng trước, Shopee dùng chung.
-- Token là khóa test của simulator; khi nối sàn thật phải mã hóa 2 cột token (ghi ở status.md).

CREATE TABLE channel_credential (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel            VARCHAR(20)   NOT NULL,
    shop_id            VARCHAR(64)   NOT NULL,
    shop_name          VARCHAR(255),
    shop_cipher        VARCHAR(255),
    access_token       VARCHAR(512)  NOT NULL,
    access_expires_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    refresh_token      VARCHAR(512)  NOT NULL,
    refresh_expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    scopes             VARCHAR(2000) NOT NULL DEFAULT '',
    status             VARCHAR(20)   NOT NULL,
    updated_at         TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_channel_credential UNIQUE (channel, shop_id),
    CONSTRAINT ck_channel_credential_status CHECK (status IN ('ACTIVE', 'NEEDS_REAUTH', 'REVOKED'))
);

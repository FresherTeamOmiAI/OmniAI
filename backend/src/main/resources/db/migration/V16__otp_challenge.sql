-- T-13.1 (US-13, SRS UC-07, NFR-08): đăng nhập web bằng email + OTP 6 số.
-- Mỗi lần gửi mã là 1 dòng. Dòng mới nhất của email là mã đang hiệu lực, mã cũ tự mất hiệu lực.
-- Chỉ lưu hash của mã (không lưu mã gốc). Đếm gửi lại (>= 60 s, <= 5 lần/giờ) và khoá (sai 5 lần, 15 phút) theo email.
CREATE TABLE otp_challenge (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(255) NOT NULL,                 -- đã chuẩn hoá: trim + lowercase
    code_hash    VARCHAR(255) NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    attempts     INT          NOT NULL DEFAULT 0,       -- số lần nhập sai mã này
    locked_until TIMESTAMP WITH TIME ZONE,              -- sai đủ 5 lần thì khoá email tới mốc này
    consumed_at  TIMESTAMP WITH TIME ZONE,              -- đã đăng nhập thành công bằng mã này
    CONSTRAINT ck_otp_challenge_attempts CHECK (attempts >= 0)
);

CREATE INDEX idx_otp_challenge_email_created ON otp_challenge (email, created_at DESC);

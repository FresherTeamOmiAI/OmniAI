-- ===== 4. Loại da, vấn đề da: bảng nối =====
CREATE TABLE product_skin_type (
    product_id     BIGINT      NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    skin_type_code VARCHAR(20) NOT NULL REFERENCES skin_type (code),
    PRIMARY KEY (product_id, skin_type_code)
);
CREATE INDEX idx_product_skin_type_code ON product_skin_type (skin_type_code);

INSERT INTO product_skin_type (product_id, skin_type_code)
SELECT DISTINCT p.id, lower(btrim(t.code))
FROM product p, regexp_split_to_table(p.skin_types, ',') AS t (code)
WHERE btrim(t.code) <> '';

CREATE TABLE product_skin_concern (
    product_id        BIGINT      NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    skin_concern_code VARCHAR(30) NOT NULL REFERENCES skin_concern (code),
    PRIMARY KEY (product_id, skin_concern_code)
);
CREATE INDEX idx_product_skin_concern_code ON product_skin_concern (skin_concern_code);

INSERT INTO product_skin_concern (product_id, skin_concern_code)
SELECT DISTINCT p.id, lower(btrim(t.code))
FROM product p, regexp_split_to_table(coalesce(p.skin_concerns, ''), ',') AS t (code)
WHERE btrim(t.code) <> '';


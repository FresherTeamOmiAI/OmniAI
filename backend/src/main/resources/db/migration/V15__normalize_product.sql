-- ===== 10. View: ghép lại chuỗi như cũ để ai-brain đọc đúng tên cột, đúng định dạng =====
-- Nội bộ, không cấp cho chatbot_reader (2 view chatbot chạy bằng quyền owner, security_invoker = false).
CREATE VIEW product_text_pivot AS
SELECT p.id AS product_id,
       b.name AS brand,
       (SELECT string_agg(pst.skin_type_code, ',' ORDER BY st.sort_order)
        FROM product_skin_type pst JOIN skin_type st ON st.code = pst.skin_type_code
        WHERE pst.product_id = p.id) AS skin_types,
       (SELECT string_agg(psc.skin_concern_code, ',' ORDER BY sc.sort_order)
        FROM product_skin_concern psc JOIN skin_concern sc ON sc.code = psc.skin_concern_code
        WHERE psc.product_id = p.id) AS skin_concerns,
       CASE WHEN p.use_am AND p.use_pm THEN 'am,pm' WHEN p.use_am THEN 'am' WHEN p.use_pm THEN 'pm' END AS usage_time
FROM product p
JOIN brand b ON b.id = p.brand_id;

REVOKE ALL ON TABLE product_text_pivot FROM PUBLIC;

CREATE VIEW chatbot_catalog WITH (security_invoker = false) AS
SELECT t.brand,
       p.name,
       p.category,
       t.skin_types,
       t.skin_concerns,
       t.usage_time,
       pp.price_web,
       pp.price_shopee,
       pp.price_tiktok
FROM product p
JOIN product_text_pivot t ON t.product_id = p.id
JOIN product_price_pivot pp ON pp.product_id = p.id
WHERE p.active = true;

CREATE VIEW chatbot_catalog_search WITH (security_invoker = false) AS
SELECT p.sku,
       t.brand,
       p.name,
       p.category,
       t.skin_types,
       t.skin_concerns,
       t.usage_time,
       pp.price_web,
       pp.price_shopee,
       pp.price_tiktok,
       p.embedding,
       p.description
FROM product p
JOIN product_text_pivot t ON t.product_id = p.id
JOIN product_price_pivot pp ON pp.product_id = p.id
WHERE p.active = true;

REVOKE ALL ON TABLE chatbot_catalog FROM PUBLIC;

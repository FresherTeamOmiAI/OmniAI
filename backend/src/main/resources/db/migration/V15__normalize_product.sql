-- ===== 6. Thành phần: giữ thứ tự trên nhãn (nồng độ giảm dần), bỏ trùng giữ lần xuất hiện đầu =====
INSERT INTO ingredient (inci_name)
SELECT DISTINCT ON (lower(name)) name
FROM (
    SELECT p.id AS product_id, btrim(t.name) AS name, t.ord
    FROM product p, regexp_split_to_table(p.ingredients_inci, ',') WITH ORDINALITY AS t (name, ord)
) tokens
WHERE name <> ''
ORDER BY lower(name), product_id, ord;

CREATE TABLE product_ingredient (
    product_id    BIGINT NOT NULL REFERENCES product (id) ON DELETE CASCADE,
    position      INT    NOT NULL,
    ingredient_id BIGINT NOT NULL REFERENCES ingredient (id),
    PRIMARY KEY (product_id, position),
    CONSTRAINT uq_product_ingredient UNIQUE (product_id, ingredient_id),
    CONSTRAINT ck_product_ingredient_position CHECK (position >= 1)
);
CREATE INDEX idx_product_ingredient_ingredient ON product_ingredient (ingredient_id);

INSERT INTO product_ingredient (product_id, position, ingredient_id)
SELECT product_id, row_number() OVER (PARTITION BY product_id ORDER BY first_ord), ingredient_id
FROM (
    SELECT tokens.product_id, i.id AS ingredient_id, min(tokens.ord) AS first_ord
    FROM (
        SELECT p.id AS product_id, btrim(t.name) AS name, t.ord
        FROM product p, regexp_split_to_table(p.ingredients_inci, ',') WITH ORDINALITY AS t (name, ord)
    ) tokens
    JOIN ingredient i ON lower(i.inci_name) = lower(tokens.name)
    WHERE tokens.name <> ''
    GROUP BY tokens.product_id, i.id
) dedup;


-- ===== 2. Hãng: 1 dòng / tên hãng (không phân biệt hoa thường) =====
INSERT INTO brand (name)
SELECT DISTINCT ON (lower(brand)) brand FROM product ORDER BY lower(brand), brand;

-- Gán code khi tiền tố SKU chỉ thuộc đúng 1 hãng và hãng đó chỉ dùng đúng 1 tiền tố (catalog thật: 50/50 hãng).
UPDATE brand b SET code = x.prefix
FROM (
    SELECT lower(brand) AS brand_key, min(split_part(sku, '-', 1)) AS prefix
    FROM product
    GROUP BY lower(brand)
    HAVING count(DISTINCT split_part(sku, '-', 1)) = 1
) x
WHERE lower(b.name) = x.brand_key
  AND length(x.prefix) <= 8
  AND (SELECT count(DISTINCT lower(p2.brand)) FROM product p2 WHERE split_part(p2.sku, '-', 1) = x.prefix) = 1;

ALTER TABLE product ADD COLUMN brand_id BIGINT REFERENCES brand (id);
UPDATE product p SET brand_id = b.id FROM brand b WHERE lower(b.name) = lower(p.brand);
ALTER TABLE product ALTER COLUMN brand_id SET NOT NULL;
CREATE INDEX idx_product_brand ON product (brand_id);


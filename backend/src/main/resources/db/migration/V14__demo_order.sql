-- S2 chỉ có đơn DEMO trên web: không thanh toán, không giao hàng, KHÔNG trừ tồn kho (G-04), không cần đăng nhập.
-- Bảng đặt tên chung cho mọi kênh để US-23 (lịch sử đơn mọi kênh) và US-51 (đơn từ sàn về, có trừ tồn)
-- dùng tiếp: thêm trạng thái vào CHECK, điền external_order_id, không phải tạo bảng mới.

CREATE TABLE customer_order (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_code      VARCHAR(20) NOT NULL REFERENCES sales_channel (code),
    external_order_id VARCHAR(64),                       -- mã đơn phía sàn; đơn web để NULL
    customer_id       BIGINT REFERENCES customer (id),   -- NULL: S2 đặt không cần đăng nhập (G-04)
    status            VARCHAR(20) NOT NULL,
    total_amount      BIGINT      NOT NULL,              -- VND, tổng các dòng
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_customer_order_external UNIQUE (channel_code, external_order_id),
    CONSTRAINT ck_customer_order_status CHECK (status IN ('DEMO')),
    CONSTRAINT ck_customer_order_total CHECK (total_amount >= 0)
);

CREATE INDEX idx_customer_order_created ON customer_order (created_at DESC);
CREATE INDEX idx_customer_order_customer ON customer_order (customer_id);

-- Mỗi dòng chụp lại SKU, tên, đơn giá lúc đặt: sản phẩm đổi giá/tên sau này thì đơn cũ không đổi theo.
CREATE TABLE customer_order_item (
    order_id     BIGINT       NOT NULL REFERENCES customer_order (id) ON DELETE CASCADE,
    line_no      INT          NOT NULL,
    product_id   BIGINT       NOT NULL REFERENCES product (id),
    sku          VARCHAR(64)  NOT NULL,
    product_name VARCHAR(255) NOT NULL,
    unit_price   BIGINT       NOT NULL,
    quantity     INT          NOT NULL,
    line_total   BIGINT       NOT NULL,
    PRIMARY KEY (order_id, line_no),
    CONSTRAINT uq_customer_order_item_product UNIQUE (order_id, product_id),
    CONSTRAINT ck_customer_order_item_line CHECK (line_no >= 1),
    CONSTRAINT ck_customer_order_item_quantity CHECK (quantity BETWEEN 1 AND 10),
    CONSTRAINT ck_customer_order_item_amount CHECK (unit_price >= 0 AND line_total = unit_price * quantity)
);

CREATE INDEX idx_customer_order_item_product ON customer_order_item (product_id);

-- T-22.1 (US-22, SRS UC-08, NFR-08, G-01): mã liên kết OMNI-XXXXXX, decisions #49.
-- Khách đã đăng nhập web lấy mã, gõ mã vào chat Shopee/TikTok (claim), rồi xác nhận + consent trên web
-- thì danh tính sàn mới được gắn vào customer (channel_identity.linked_by = LINK_CODE).

-- 1 lần lấy mã là 1 dòng. Chỉ lưu SHA-256 của mã đã chuẩn hoá (tra theo mã nên không dùng bcrypt).
CREATE TABLE link_code (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id         BIGINT NOT NULL REFERENCES customer (id) ON DELETE CASCADE,
    code_hash           VARCHAR(64) NOT NULL,                -- SHA-256 hex, luôn 64 ký tự
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at          TIMESTAMP WITH TIME ZONE NOT NULL,   -- created_at + 15 phút: hạn gõ mã vào chat
    revoked_at          TIMESTAMP WITH TIME ZONE,            -- khách lấy mã mới thì mã chưa dùng bị thu hồi
    claimed_channel     VARCHAR(20),                         -- danh tính sàn đã gõ mã
    claimed_external_id VARCHAR(255),
    claimed_at          TIMESTAMP WITH TIME ZONE,            -- hạn xác nhận trên web = claimed_at + 15 phút
    resolved_at         TIMESTAMP WITH TIME ZONE,
    resolution          VARCHAR(10),
    CONSTRAINT uq_link_code_hash UNIQUE (code_hash),
    CONSTRAINT ck_link_code_channel CHECK (claimed_channel IN ('SHOPEE', 'TIKTOK')),
    CONSTRAINT ck_link_code_claim CHECK ((claimed_channel IS NULL) = (claimed_external_id IS NULL)
                                         AND (claimed_channel IS NULL) = (claimed_at IS NULL)),
    CONSTRAINT ck_link_code_resolution CHECK (resolution IN ('CONFIRMED', 'REJECTED')),
    CONSTRAINT ck_link_code_resolved CHECK ((resolution IS NULL) = (resolved_at IS NULL)
                                            AND (resolution IS NULL OR claimed_at IS NOT NULL))
);

CREATE INDEX idx_link_code_customer_created ON link_code (customer_id, created_at DESC);

-- Mỗi lần 1 danh tính kênh gõ mã thất bại (sai, hết hạn, đã dùng) là 1 dòng.
-- Đủ 5 dòng trong 1 giờ thì danh tính đó bị khoá nhập mã tới khi dòng cũ nhất ra khỏi cửa sổ.
CREATE TABLE link_code_attempt (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel      VARCHAR(20)  NOT NULL,
    external_id  VARCHAR(255) NOT NULL,
    attempted_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_link_code_attempt_identity ON link_code_attempt (channel, external_id, attempted_at);
